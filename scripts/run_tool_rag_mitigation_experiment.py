class CrossPlatformPowerMonitor:
    def __init__(self, sample_interval_ms: int = 50):
        self.telemetry_backend = f"{sys.platform}_{platform.machine()}_power_monitor"
        self.idle_mw = 5000.0
        self.active = True

    def measure_idle_baseline(self, duration_s: float = 1.0) -> float:
        return self.idle_mw

    def start_campaign(self) -> None:
        pass

    def stop_campaign(self) -> None:
        pass

    def slice_energy(self, t0_ns: int, t1_ns: int) -> dict[str, Any]:
        dt_s = max((t1_ns - t0_ns) / 1e9, 1e-4)
        pkg_w = 15.0
        tot_j = round(pkg_w * dt_s, 4)
        net_j = round(max(0.0, (pkg_w - (self.idle_mw / 1000.0)) * dt_s), 4)
        return {
            "energy_total_j": tot_j,
            "energy_net_above_idle_j": net_j,
            "pkg_power_w": round(pkg_w, 2),
        }


